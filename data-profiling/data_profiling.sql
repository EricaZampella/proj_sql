/*Top 10 customers*/
SELECT 
c.cst_fullname,
SUM(s.sls_sales) AS revenue,
DENSE_RANK() OVER (ORDER BY SUM(s.sls_sales) DESC) as top_10_customers
FROM crm_customer_sylver c
LEFT JOIN crm_sales_sylver s
ON c.cst_id= s.sls_cust_id
GROUP BY c.cst_fullname
LIMIT 10;
/*Top 10 minor customers*/
SELECT 
c.cst_fullname,
SUM(s.sls_sales) AS revenue,
DENSE_RANK() OVER (ORDER BY SUM(s.sls_sales) ASC) as top_10_customers
FROM crm_customer_sylver c
LEFT JOIN crm_sales_sylver s
ON c.cst_id= s.sls_cust_id
